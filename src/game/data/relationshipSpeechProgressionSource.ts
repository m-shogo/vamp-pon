export const currentRelationshipSpeechProgressionEntries: readonly CurrentRelationshipSpeechProgressionEntry[] =
  seeds.map((seed) => {
    const relation = currentRelationshipInventoryById.get(seed.relationId);
    if (!relation) throw new Error(`missing Current relationship for speech progression: ${seed.relationId}`);
    const [a, b] = relation.participants;
    const participants = new Set([a, b]);
    for (const item of seed.tracks) {
      if (!participants.has(item.speakerId) || !participants.has(item.targetId) || item.speakerId === item.targetId) {
        throw new Error(`speech track participant drift: ${seed.relationId}`);
      }
    }
    return {
      relationId: seed.relationId,
      tracks: seed.tracks,
      romanceBoundary: seed.romanceBoundary ?? 'UNRESOLVED_BY_THIS_SOURCE',
      numericBondThresholdsLocked: false,
      storyGateRequired: relation.detailedMachineArcAvailable,
      authority: 'CONTENT_SOURCE_ONLY',
      runtimeAutoPromotionAllowed: false,
    };
  });

